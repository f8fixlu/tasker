export const Icon = ({ name, className = '', spin = false, size, ...props }) => {
  const LucideIcon = ICON_MAP[name];
  if (!LucideIcon) return null;
  const spinClass = spin || name === 'progress_activity' ? 'animate-spin' : '';
  return <LucideIcon className={`${spinClass} ${className}`.trim()} size={size} {...props} />;
};
